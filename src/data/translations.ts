export type TranslationDictionary = typeof translations.en;

/**
 * Helper to get a translation by dot notation path (e.g. "nav.home")
 * Falls back to English if key is missing in chosen language.
 * Warns in console if key is completely missing.
 */
export function translate(
  lang: SupportedLanguage,
  path: string,
  params?: Record<string, string | number>,
): string {
  const getNested = (obj: unknown, keys: string[]): unknown => {
    let current = obj as Record<string, unknown> | undefined | null;
    for (const k of keys) {
      if (current === undefined || current === null) return undefined;
      current = current[k] as Record<string, unknown> | undefined | null;
    }
    return current;
  };

  const keys = path.split(".");
  const langObj = translations[lang] || translations.en;
  let val = getNested(langObj, keys);

  if (val === undefined || val === null) {
    // Fallback to English
    val = getNested(translations.en, keys);
    if (val === undefined || val === null) {
      if (
        typeof process !== "undefined" &&
        process.env &&
        process.env["NODE_ENV"] !== "production"
      ) {
        console.warn(`[i18n] Missing translation key: "${path}" for language: "${lang}"`);
      }
      return path;
    }
  }

  if (typeof val !== "string") {
    return String(val);
  }

  if (params) {
    let result = val;
    for (const [k, v] of Object.entries(params)) {
      result = result.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
    return result;
  }

  return val;
}
